// Builds the loader's page host from the game source, with the source's own esbuild:
//   core/core.js    core/src/core-entry.mjs bundled with the game's own Mod API (src/mods/modApi.js, moduleHost.js, keysPanel.js),
//                   so a module judged here is judged exactly as the game's native host judges it;
//   core/modapi.mjs the game's src/mods/modApi.js alone, for check.cjs (which judges the installed modules with it).
// Neither needs the source at run time. Rebuild after pulling new game source (tools/sync.mjs does it for you).
//
//   node build-core.mjs [--source <daggerfall-js-source folder>]     default: ../../daggerfall-js-source (beside this repo)
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const at = process.argv.indexOf('--source');
const source = resolve(at >= 0 ? process.argv[at + 1] : join(here, '..', '..', 'daggerfall-js-source'));
const esbuild = createRequire(join(source, 'package.json'))('esbuild');

const common = { bundle: true, platform: 'browser', target: 'es2022', minify: false, logLevel: 'info', alias: { '@game': source } };
const banner = (what) => ({ js: `// GENERATED by build-core.mjs from ${what} - do not edit. Contains the game's own Mod API (MIT, Lattymoy).` });
const results = await Promise.all([
  esbuild.build({ ...common, entryPoints: [join(here, 'core', 'src', 'core-entry.mjs')], outfile: join(here, 'core', 'core.js'), format: 'iife', banner: banner('core/src/core-entry.mjs') }),
  esbuild.build({ ...common, entryPoints: [join(source, 'src', 'mods', 'modApi.js')], outfile: join(here, 'core', 'modapi.mjs'), format: 'esm', banner: banner('daggerfall-js-source/src/mods/modApi.js') }),
]);
if (results.some((r) => r.errors.length)) process.exit(1);
