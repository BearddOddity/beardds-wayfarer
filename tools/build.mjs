// Builds the mod from its source: source/<id>/ -> Mods/<id>/, the folders players install.
//
//   - A module written as several files keeps them in source/<id>/src/; they are bundled into source/<id>/module.js (the game
//     imports a module's entry from a blob, so it cannot import a sibling file at run time).
//   - Each module's module.json and module.js are copied to Mods/<id>/, with the entry's SHA-256 written into the manifest, so
//     the game refuses a changed or damaged copy.
//   - Every module carries the version in package.json, so the three always ship together.
//   - The mod's words, for the game's translators: game-integration/wayfarer-strings.csv (see game-integration/README.md).
//
//   npm run build
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(repo, 'source');
const out = join(repo, 'Mods');
const { version } = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8'));
const ids = readdirSync(source).filter((d) => statSync(join(source, d)).isDirectory() && existsSync(join(source, d, 'module.json')));

rmSync(out, { recursive: true, force: true });
for (const id of ids) {
  const dir = join(source, id);
  const manifestFile = join(dir, 'module.json');
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
  if (manifest.id !== id) throw new Error(`source/${id}: its module.json says id '${manifest.id}'`);
  if (manifest.version !== version) {   // the version lives in package.json: the source's manifest follows it
    manifest.version = version;
    writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  }
  if (existsSync(join(dir, 'src', 'setup.js'))) {
    await build({
      entryPoints: [join(dir, 'src', 'setup.js')], outfile: join(dir, 'module.js'),
      bundle: true, format: 'esm', platform: 'browser', target: 'es2020', minify: false, logLevel: 'warning',
      banner: { js: `// GENERATED by tools/build.mjs from source/${id}/src - do not edit.` },
    });
  }
  const entry = manifest.entry ?? 'module.js';
  const code = readFileSync(join(dir, entry), 'utf8');
  mkdirSync(join(out, id), { recursive: true });
  writeFileSync(join(out, id, entry), code);
  writeFileSync(join(out, id, 'module.json'), `${JSON.stringify({ ...manifest, sha256: createHash('sha256').update(code, 'utf8').digest('hex') }, null, 2)}\n`);
  console.log(`built Mods/${id} ${version}`);
}

// THE MOD'S WORDS for the game's translators: every tx('module.<id>.<word>', 'English') in the hand-written source (not the
// generated bundle), as one string table in the game's own format (Key,Value) - the rows the game's catalog takes in, so the
// game's own pipeline translates them with the rest of its words
const handWritten = (dir) => readdirSync(dir).flatMap((name) => {
  const p = join(dir, name);
  if (statSync(p).isDirectory()) return handWritten(p);
  const generated = name === 'module.js' && existsSync(join(dir, 'src'));
  return name.endsWith('.js') && !generated ? [p] : [];
});
const words = new Map();
for (const file of handWritten(source)) {
  for (const [, key, en] of readFileSync(file, 'utf8').matchAll(/tx\('(module\.[\w.]+)', '([^'\\]*)'/g)) {
    if (words.has(key) && words.get(key) !== en) throw new Error(`${key}: two Englishes, '${words.get(key)}' and '${en}'`);
    words.set(key, en);
  }
}
const rows = [...words].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `${k},"${v.replace(/"/g, '""')}"`);
writeFileSync(join(repo, 'game-integration', 'wayfarer-strings.csv'), `${['Key,Value', ...rows].join('\n')}\n`);
console.log(`words: ${words.size} -> game-integration/wayfarer-strings.csv`);
